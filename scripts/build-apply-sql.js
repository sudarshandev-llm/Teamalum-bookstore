// Concatenates every migration in supabase/migrations into one pasteable file.
// Usage: node scripts/build-apply-sql.js
// Output: supabase/APPLY_NOW.sql
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const migrationsDir = path.join(root, 'supabase', 'migrations');
const outFile = path.join(root, 'supabase', 'APPLY_NOW.sql');

const files = fs
  .readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort();

if (!files.length) {
  console.error('No migrations found in ' + migrationsDir);
  process.exit(1);
}

const header = [
  '-- =============================================================================',
  '--  Team Alum Bookstore — full database setup (paste into Supabase SQL Editor)',
  '--  Project ref : gvkcwtoryrzgbtufsgff',
  '--  Generated by : npm run db:build  (scripts/build-apply-sql.js)',
  '--',
  '--  HOW TO APPLY',
  '--    1. Open https://supabase.com/dashboard/project/gvkcwtoryrzgbtufsgff/sql/new',
  '--    2. Paste the whole contents of this file and press Run.',
  '--    3. It is safe to run more than once — every statement is idempotent.',
  '-- =============================================================================',
  '',
].join('\n');

const body = files
  .map((f) => {
    const sql = fs.readFileSync(path.join(migrationsDir, f), 'utf8').trim();
    return [
      '',
      '-- =============================================================================',
      `--  ${f}`,
      '-- =============================================================================',
      sql,
      '',
    ].join('\n');
  })
  .join('\n');

fs.writeFileSync(outFile, header + body, 'utf8');

const kb = (Buffer.byteLength(header + body, 'utf8') / 1024).toFixed(1);
console.log(`Wrote ${path.relative(root, outFile)}  (${files.length} migration(s), ${kb} KB)`);
for (const f of files) console.log('  + ' + f);
